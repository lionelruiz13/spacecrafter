#!/usr/bin/env bash
#
# deploy.sh -- the opus-xhigh executor's DEPLOYED PROJECTION: one generator,
#              one check, no second authority.
#
#     ./deploy.sh            write ../../.claude/agents/opus-xhigh.md
#     ./deploy.sh --check    regenerate to a temp file and compare byte-exact;
#                            exit 1 on drift (the supervisor's warm-up assert,
#                            fable-dispatch.md section 0b step 1)
#
# WHAT THE PROJECTION IS. Claude Code loads a subagent's whole system prompt
# from the markdown body of .claude/agents/<name>.md (frontmatter: name,
# description, model, effort). Since 2026-10-10 [vixy: "add the
# system-prompt.txt as well, to opus-xhigh"] that body is THREE parts:
#
#     1. the OWNER's system prompt, verbatim, as assembled by
#        ~/shared/system-prompt-parts/assemble.sh into
#        /home/claude/shared/system-prompt.txt -- the architecture window, the
#        invariants I1-I9, the preferences, the discharge rules;
#     2. a BRIDGE block (below): precedence between the three parts, the two
#        scopings an executor needs, the definition stamp, the start gate;
#     3. the executor's own definition -- the body of claude/agents/opus-xhigh.md
#        (responsibility, premises, constraints, states), the tracked AUTHORITY.
#
# WHY A GENERATOR AND NOT A COPY. The prompt is the owner's artifact, edited in
# its parts and re-assembled; the fable-asi-* agents are re-emitted by that
# same assembly. A copy of it pasted into opus-xhigh.md would be a manual
# resynchronisation awaiting silent drift (I2). So the projection is DERIVED
# at use from the two primary artifacts (I8), the derivation is deterministic
# (no timestamp: the same inputs give the same bytes), and the projection
# names its inputs by md5 in its own header, so `--check` is a byte-exact
# comparison and a dispatch can prove which definition it ran on. Push rather
# than poll (I3) would have assemble.sh call this after every assembly; that
# couples the owner's prompt tooling to one project, so the barrier is at the
# use site instead: the warm-up runs `--check` before every dispatch, and a
# stale projection cannot reach an executor.
#
# The projection is git-ignored by the code repository (`.claude/` is not
# tracked) and never tracked anywhere: it is the output of this script.
set -euo pipefail

HERE=$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")      # claude/agents
HARNESS=$(dirname "${HERE}")                               # claude
CODE=$(dirname "${HARNESS}")                               # the code tree
AUTHORITY="${HERE}/opus-xhigh.md"
PROMPT="${OPUS_XHIGH_PROMPT:-/home/claude/shared/system-prompt.txt}"   # the SHARED home, not $HOME: two users, one file
OUT="${CODE}/.claude/agents/opus-xhigh.md"

[ -f "${AUTHORITY}" ] || { echo "error: authority ${AUTHORITY} missing." >&2; exit 1; }
[ -f "${PROMPT}" ]    || { echo "error: owner prompt ${PROMPT} missing (OPUS_XHIGH_PROMPT=<path> to point elsewhere)." >&2; exit 1; }

AUTH_MD5=$(md5sum "${AUTHORITY}" | cut -c1-8)
PROMPT_MD5=$(md5sum "${PROMPT}" | cut -c1-8)

# The authority's frontmatter ends at the SECOND '---' line; everything after
# it is the executor's definition body.
FM_END=$(awk 'NR>1 && $0=="---" {print NR; exit}' "${AUTHORITY}")
[ -n "${FM_END}" ] || { echo "error: ${AUTHORITY} has no closing frontmatter '---'." >&2; exit 1; }

generate() {
    # frontmatter, with the generation line as a YAML comment (assemble.sh's form)
    sed -n "1,$((FM_END - 1))p" "${AUTHORITY}"
    printf '# GENERATED by claude/agents/deploy.sh from claude/agents/opus-xhigh.md (md5 %s) + /home/claude/shared/system-prompt.txt (md5 %s) -- never edit; re-run deploy.sh\n' "${AUTH_MD5}" "${PROMPT_MD5}"
    echo '---'
    # 1. the owner's prompt, verbatim
    cat "${PROMPT}"
    # 2. the bridge
    cat <<EOF
<executor-bridge>
You are the \`opus-xhigh\` EXECUTOR (Claude Opus 5.5, effort xhigh) of ONE dispatched spacecrafter task, running under the OWNER's system prompt -- everything above this block -- since 2026-10-10 [vixy: "add the system-prompt.txt as well, to opus-xhigh"]: the architecture window, the programming invariants I1-I9, the preferences and the discharge rules bind your reasoning exactly as they bind the supervising session's.
Precedence where the texts differ: the DISPATCH PROMPT (per-round variables, boundaries) > the executor definition BELOW this block > the owner's prompt ABOVE it -- the specific over the general, never the reverse. Two scopings follow [derived by the supervising session, veto-open]: (1) the session-start read-binding of the queue (\`~/shared/QUEUE.md\`) and the standing commit licence stated above are the SUPERVISING session's duties -- your start surface is \`claude/fable-dispatch.md\` section 0 (the warm-up), and you commit only what the dispatch prompt says you commit (default since 2026-09-19: nothing); (2) a finding of the cross-project kind (a monitor firing on something beyond this task) goes into your delivery report, where the supervisor routes it -- the persistence-discharge rule is met by that report line, never by a write to the queue from an executor.
Definition stamp: authority \`claude/agents/opus-xhigh.md\` md5 ${AUTH_MD5} over \`system-prompt.txt\` md5 ${PROMPT_MD5} -- quote this line verbatim when asked which definition you run on.
Start-of-task gate (task-initiation monitor): confirm that the architecture window block -- seed L0-L4, operating loop, monitors, router -- is present ABOVE this block in your own system prompt. If it is, the FIRST line of your return message to the dispatcher reads exactly: prompt-window: present. If it is not, your ONLY output is: prompt-window: absent -- stop; do not run the task.
</executor-bridge>

EOF
    # 3. the executor's definition
    sed -n "$((FM_END + 1)),\$p" "${AUTHORITY}"
}

case "${1:-}" in
    --check)
        TMP=$(mktemp); trap 'rm -f "${TMP}"' EXIT
        generate > "${TMP}"
        if [ -f "${OUT}" ] && cmp -s "${TMP}" "${OUT}"; then
            echo "opus-xhigh projection CURRENT: ${OUT} = generate(authority ${AUTH_MD5}, prompt ${PROMPT_MD5}), md5 $(md5sum "${OUT}" | cut -c1-8)"
            exit 0
        fi
        echo "opus-xhigh projection STALE or missing: ${OUT}" >&2
        echo "  expected = generate(authority ${AUTH_MD5}, prompt ${PROMPT_MD5}); run: bash claude/agents/deploy.sh" >&2
        if [ -f "${OUT}" ]; then diff "${OUT}" "${TMP}" | head -12 >&2; fi
        exit 1 ;;
    "")
        mkdir -p "$(dirname "${OUT}")"
        TMP=$(mktemp); trap 'rm -f "${TMP}"' EXIT
        generate > "${TMP}"
        cp "${TMP}" "${OUT}"; chmod 664 "${OUT}" 2>/dev/null || true
        echo "opus-xhigh projection written: ${OUT} ($(wc -c < "${OUT}") bytes, md5 $(md5sum "${OUT}" | cut -c1-8)) from authority ${AUTH_MD5} + prompt ${PROMPT_MD5}" ;;
    *)
        echo "usage: $0 [--check]" >&2; exit 1 ;;
esac
